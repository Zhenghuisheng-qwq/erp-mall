import { createRequire } from 'node:module'

const require = createRequire('D:/tmp/pw/package.json')
const { chromium } = require('playwright-core')
const base = process.env.SMOKE_URL || 'http://127.0.0.1:5237'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const notes = []
let clicks = 0
async function click(locator, label) {
  await locator.click()
  clicks += 1
  notes.push(`点击 ${clicks}：${label}`)
}
try {
  await page.goto(`${base}/compatibility`, { waitUntil: 'networkidle' })
  notes.push('打开适用关系')
  await click(page.getByRole('button', { name: '放入测试样例' }), '放入测试样例')
  await page.locator('.panel').getByText('不是 Excel').waitFor()
  const search = page.getByPlaceholder('搜品牌、系列或型号')
  await search.fill('iPhone 17 Pro Max')
  await click(page.getByRole('button', { name: /iPhone 17 Pro Max/ }), '选中 iPhone 17 Pro Max')
  await click(page.getByRole('button', { name: '添加配件' }), '添加配件')
  await click(page.locator('.el-drawer').getByRole('button', { name: '屏幕膜' }), '只看屏幕膜')
  const film = page.locator('.el-drawer label').filter({ hasText: '【测试样例】高清膜' })
  await film.waitFor()
  await click(film.locator('input'), '勾选高清膜')
  await click(page.getByRole('button', { name: '确认关联 1 条' }), '确认关联')
  await page.locator('.panel').getByText('新增 1 条').waitFor()
  notes.push('老板：高清膜已挂到 17 Pro Max')
  await click(page.getByRole('button', { name: '继续关联其他主机' }), '从这条膜继续选主机')
  await page.getByText('勾选主机后一次保存').waitFor()
  const second = page.locator('label').filter({ hasText: 'iPhone 18 Pro Max' })
  await click(second.locator('input'), '勾选 iPhone 18 Pro Max')
  await click(page.getByRole('button', { name: '关联到 1 款主机' }), '一次挂上第二款主机')
  await page.locator('.panel').getByText('新增 1 条').waitFor()
  if (!(await page.locator('.panel').last().innerText()).includes('iPhone 18 Pro Max')) throw new Error('第二款主机没有出现')
  notes.push('老板：没有重新查找保护膜')
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByText('iPhone 17 Pro Max').first().waitFor()
  await page.getByText('iPhone 18 Pro Max').first().waitFor()
  notes.push('刷新后两款主机还在')

  await page.goto(`${base}/products`, { waitUntil: 'networkidle' })
  const productSearch = page.getByPlaceholder('名称、分类、属性、SKU、OA 编号')
  await productSearch.fill('【测试样例】保护壳')
  await productSearch.press('Enter')
  await click(page.getByRole('button', { name: '适用主机' }).first(), '新员工从商品列表进入适用主机')
  await page.getByText('【测试样例】保护壳').first().waitFor()
  const hostPick = page.locator('label').filter({ hasText: 'iPhone 17 Pro Max' })
  await click(hostPick.locator('input'), '勾选主机')
  await click(page.getByRole('button', { name: /关联到 1 款主机/ }), '保存适用主机')
  await page.locator('.panel').getByText('新增 1 条').waitFor()
  notes.push('新员工：保护壳档案外就能看到并添加适用主机')

  await page.goto(`${base}/compatibility`, { waitUntil: 'networkidle' })
  await page.getByPlaceholder('搜品牌、系列或型号').fill('iPhone 17 Pro Max')
  await click(page.getByRole('button', { name: /iPhone 17 Pro Max/ }), '运营回到这款主机')
  await click(page.getByRole('button', { name: '添加配件' }), '批量添加')
  await click(page.locator('.el-drawer').getByRole('button', { name: '屏幕膜' }), '筛选屏幕膜')
  const secondFilm = page.locator('.el-drawer label').filter({ hasText: '【测试样例】防窥膜' })
  await click(secondFilm.locator('input'), '勾选防窥膜')
  await click(page.getByRole('button', { name: '确认关联 1 条' }), '确认批量里的新膜')
  await page.locator('.panel').getByText(/新增 1 条，已存在 0 条/).waitFor()
  await click(page.getByRole('button', { name: '添加配件' }), '再打开一次已有关系')
  await click(page.locator('.el-drawer').getByRole('button', { name: '屏幕膜' }), '仍然只看屏幕膜')
  await page.locator('.el-drawer').getByText('已经关联').first().waitFor()
  notes.push('运营：已关联的膜标了出来，确认按钮不会重复写入')
  await page.keyboard.press('Escape')
  await page.locator('.el-drawer').waitFor({ state: 'hidden' })
  await click(page.locator('.layout .panel').last().getByRole('button', { name: '屏幕膜' }), '按屏幕膜筛选已关联列表')
  const code = (await page.locator('body').innerText()).match(/MAT-\d+/)?.[0]
  if (!code) throw new Error('列表里没有物料编码')
  await page.getByPlaceholder('搜物料编码或名称').fill(code)
  await page.getByText(code).first().waitFor()
  notes.push(`运营：按编码 ${code} 找到配件`)
  const row = page.locator('.choice').filter({ hasText: code }).first()
  await click(row.locator('input'), '勾选要取消的关系')
  await click(page.getByRole('button', { name: /取消 1 条关联/ }), '取消一条')
  await page.getByText('取消了 1 条关联').waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByPlaceholder('搜品牌、系列或型号').fill('iPhone 17 Pro Max')
  await page.getByRole('button', { name: /iPhone 17 Pro Max/ }).click()
  notes.push(`老板到运营一共记录 ${clicks} 次点击，刷新后关系仍在`)
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
} catch (error) {
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
  console.error('FAIL', error)
  process.exitCode = 1
} finally {
  await browser.close()
}
