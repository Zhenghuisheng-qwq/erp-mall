import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'

const require = createRequire(existsSync('D:/tmp/pw/package.json') ? 'D:/tmp/pw/package.json' : import.meta.url)
const { chromium } = require('playwright-core')
const base = process.env.SMOKE_URL || 'http://127.0.0.1:5217'
const browser = await chromium.launch({ channel: 'chrome', headless: true })

async function run() {
  const boss = []
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(`${base}/specs?template=t-phone`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: '发布模型' }).click()
  boss.push('发布模型')
  await page.getByText('16 条已有规划编号').waitFor()
  const box = page.locator('.combo-check input').first()
  await box.check()
  boss.push('勾选一条规划')
  await page.getByRole('button', { name: '标为核心商品' }).click()
  boss.push('标为核心商品')
  await page.getByText('待创建物料').first().waitFor()
  await page.locator('.combo-preview button').filter({ hasText: '待创建物料' }).first().click()
  boss.push('选中核心规划')
  await page.getByRole('button', { name: '创建物料', exact: true }).click()
  boss.push('创建物料')
  await page.getByRole('button', { name: '确认创建' }).click()
  boss.push('确认创建')
  await page.getByText('已有 1 条物料').first().waitFor()
  if (await page.getByText('下面直接加规格').count()) throw new Error('模型页不该出现旧文案')

  const newbie = []
  await page.getByRole('button', { name: '创建临时物料' }).click()
  newbie.push('创建临时物料')
  const dialog = page.getByRole('dialog', { name: '创建临时物料' })
  await dialog.waitFor()
  const manual = dialog.getByRole('button', { name: '改为手工填写' }).first()
  await manual.click()
  newbie.push('改为手工填写')
  if (!(await dialog.innerText()).includes('不会自动加入属性词典')) throw new Error('没有说明手工值不会进词典')
  await dialog.getByPlaceholder(/填写/).first().fill('特殊紫色')
  newbie.push('填写未预置颜色')
  await dialog.getByPlaceholder('例如 MAT-900001 或业务自己的编码').fill('HAND-9001')
  newbie.push('填写物料编码')
  await dialog.getByRole('button', { name: '保存临时物料' }).click()
  newbie.push('保存临时物料')
  const toast = page.getByText(/已创建临时物料|请填写|已被其他物料使用|请至少填写/)
  await toast.first().waitFor()
  const toastText = await toast.first().innerText()
  if (!toastText.includes('HAND-9001')) throw new Error('临时保存没有成功：' + toastText + '\n' + await dialog.innerText())
  await dialog.getByPlaceholder(/填写/).first().fill('特别容量')
  await dialog.getByPlaceholder('例如 MAT-900001 或业务自己的编码').fill('HAND-9002')
  await dialog.getByRole('button', { name: '保存临时物料' }).click()
  newbie.push('保存第二条临时物料')
  await page.getByText('已创建临时物料 HAND-9002').waitFor()
  await dialog.getByRole('button', { name: '查看刚创建的物料' }).click()
  newbie.push('查看刚创建的物料')
  await page.waitForURL(/\/products\//)
  await page.getByText('只属于这条物料').waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByText('只属于这条物料').waitFor()
  const code = await page.locator('.sheet label').filter({ hasText: '系统物料编码' }).locator('input').inputValue()
  if (code !== 'HAND-9002') throw new Error('刷新后编码变了 ' + code)

  const operator = []
  await page.goto(`${base}/specs?template=t-phone`, { waitUntil: 'networkidle' })
  const checks = page.locator('.combo-check input')
  await checks.nth(1).check()
  await checks.nth(2).check()
  operator.push('勾选两条规划')
  await page.getByRole('button', { name: '标为一般产品' }).click()
  operator.push('标为一般产品')
  await page.getByText('暂未创建物料').first().waitFor()
  await page.locator('.combo-preview button').filter({ hasText: '暂未创建物料' }).first().click()
  operator.push('选中一般产品')
  await page.getByRole('button', { name: '创建物料', exact: true }).click()
  const createDialog = page.getByRole('dialog', { name: '创建物料' })
  await createDialog.locator('label').filter({ hasText: '供应商编码' }).locator('input').fill('SUP-9')
  operator.push('填写供应商编码')
  await createDialog.getByRole('button', { name: '确认创建' }).click()
  operator.push('确认创建')
  await page.getByText('已有 1 条物料').first().waitFor()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('iyge-v2-mock-db')))
  const skus = stored.data.skus.filter((item) => item.materialCode)
  const codes = skus.map((item) => item.materialCode)
  if (new Set(codes).size !== codes.length) throw new Error('编码重复 ' + codes.join(','))
  if (!skus.some((item) => item.materialCode === 'HAND-9001') || !skus.some((item) => item.materialCode === 'HAND-9002' && item.manualAttrs?.some((attr) => attr.source === 'manual'))) throw new Error('临时物料丢了')
  if (stored.data.families.find((item) => item.id === 'f-iphone')?.line) throw new Error('旧商品被改了')
  console.log(JSON.stringify({ ok: true, boss: boss.length, newbie: newbie.length, operator: operator.length, codes }, null, 2))
  await page.close()
}

try {
  await run()
} finally {
  await browser.close()
}
