import { createRequire } from 'node:module'
import { readdirSync } from 'node:fs'
import { join } from 'node:path'

const require = createRequire('D:/tmp/pw/package.json')
const { chromium } = require('playwright-core')
const base = process.env.SMOKE_URL || 'http://127.0.0.1:5235'
const root = 'D:/单子/商城erp/前期包/2.0 数据'
const file = join(root, readdirSync(root).find((item) => item.includes('1.1') && item.endsWith('.xlsx')))
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const notes = []
try {
  await page.goto(`${base}/import`, { waitUntil: 'networkidle' })
  await page.locator('input[type=file][accept=".xlsx,.xls"]').setInputFiles(file)
  await page.getByText('手机 Apple').first().waitFor()
  await page.getByRole('button', { name: '预览导入' }).click()
  await page.getByText('正式可导入 0 行').waitFor()
  const before = await page.locator('body').innerText()
  if (!before.includes('平板电脑') || !before.includes('保护壳')) throw new Error('没有指出平板或保护壳缺口')
  if (before.includes('对不上正式规划的行，按临时物料导入')) throw new Error('临时导入又变成了默认开关')
  notes.push('预览先说明分类和产品类型缺口，没有默认临时导入')
  await page.getByText('容量「128GB」和模型里的「128G」').click()
  await page.getByText('正式可导入 0 行').waitFor()
  notes.push('确认容量对照后也不会把 iPhone 16 写进去')
  await page.getByRole('button', { name: '补上已核对的手机、平板、保护壳模型' }).click()
  await page.getByRole('button', { name: '用 Apple 手机 匹配' }).waitFor()
  notes.push('补模型后要求指定手机用哪一个已发布模型')
  await page.getByRole('button', { name: '用 Apple 手机 匹配' }).click()
  await page.getByText('正式可导入 583 行').waitFor({ timeout: 20000 })
  notes.push('583 行匹配正式规划')
  await page.getByRole('button', { name: '确认导入 583 行' }).click()
  const result = page.locator('p.muted').filter({ hasText: '新写入' })
  await result.waitFor({ timeout: 60000 })
  const resultText = await result.innerText()
  if (!resultText.includes('新写入 583')) throw new Error(resultText)
  notes.push(resultText)
  await page.getByRole('button', { name: /确认导入/ }).click()
  await page.locator('p.muted').filter({ hasText: '新写入 0' }).waitFor({ timeout: 60000 })
  notes.push('再次确认没有新增')
  await page.goto(`${base}/products`, { waitUntil: 'networkidle' })
  const search = page.getByPlaceholder('名称、分类、属性、SKU、OA 编号')
  await search.fill('MYEV3CH/A')
  await search.press('Enter')
  await page.getByText('Apple iPhone 16').first().waitFor()
  await page.locator('.el-table__expand-icon').first().click()
  await page.getByText('128GB 黑色').first().waitFor()
  const rowText = await page.locator('.el-table__expanded-cell').innerText()
  if (rowText.includes('TMP-') || !rowText.includes('MYEV3CH/A') || !rowText.includes('PLN-')) throw new Error(rowText)
  notes.push('黑色手机挂在 PLN，供应商编码还在')
  await search.fill('MD7W4CH/A')
  await search.press('Enter')
  await page.locator('.el-table__expand-icon').first().click()
  const padText = await page.locator('.el-table__expanded-cell').innerText()
  if (padText.split('MD7W4CH/A').length < 3) throw new Error('同供应商的两条平板没有同时留下')
  notes.push('MD7 的银色和黄色仍是两条物料')
  await page.goto(`${base}/specs?template=t-phone`, { waitUntil: 'networkidle' })
  await page.getByText('合法组合 16 条').waitFor()
  notes.push('原手机模型仍是 16 条组合')
  await page.goto(`${base}/specs?template=t-excel-case`, { waitUntil: 'networkidle' })
  await page.getByText('保护壳').first().waitFor()
  notes.push('保护壳模型单独存在')
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
} catch (error) {
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
  console.error('FAIL', error)
  process.exitCode = 1
} finally {
  await browser.close()
}
