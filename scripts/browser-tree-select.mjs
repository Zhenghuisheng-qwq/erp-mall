async function readDigest(page) {
  return page.evaluate(() => {
    const raw = JSON.parse(localStorage.getItem('iyge-v2-mock-db') || '{"data":{}}')
    const data = raw.data || {}
    const pack = (rows, map) => (rows || []).map(map).join('|')
    return {
      plans: pack(data.planningRecords, (item) => item.planningId),
      mats: pack(data.skus, (item) => `${item.id}:${item.materialCode || ''}:${item.planningId || ''}`),
      versions: JSON.stringify(data.specModelVersions || []),
      categories: pack(data.categories, (item) => `${item.id}:${item.name}:${item.parentId}`),
      types: pack(data.productTypes, (item) => `${item.id}:${item.name}:${item.categoryId}`),
      models: pack(data.specCanvases, (item) => `${item.templateId}:${item.productTypeId || ''}:${item.status}`),
    }
  })
}

