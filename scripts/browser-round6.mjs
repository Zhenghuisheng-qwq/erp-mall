import { createRequire } from 'node:module'
import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const require = createRequire('D:/tmp/pw/package.json')
const { chromium } = require('playwright-core')
const base = process.env.SMOKE_URL || 'http://127.0.0.1:5229'
const root = 'D:/单子/商城erp/前期包/2.0 数据'
const fileName = readdirSync(root).find((item) => item.includes('1.1') && item.endsWith('.xlsx'))
if (!fileName) throw new Error('没有真实 Excel')
const file = join(root, fileName)
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const notes = []
try {
  await page.goto(`${base}/import`, { waitUntil: 'networkidle' })
  await page.locator('input[type=file][accept=".xlsx,.xls"]').setInputFiles(file)
  await page.getByText('手机 Apple').first().waitFor()
  notes.push('上传并识别工作表')
  const sheetText = await page.locator('.sheet').allInnerTexts()
  if (!sheetText.some((item) => item.includes('手机 Apple') && item.includes('可以预览'))) throw new Error('物料表没有被识别\n' + sheetText.join('\n'))
  if (!sheetText.some((item) => item.includes('属性的定义') && item.includes('不导入'))) throw new Error('属性定义表被当成可导入')
  if (!sheetText.some((item) => item.includes('增值服务') && item.includes('不导入'))) throw new Error('增值服务被当成可导入')
  if (!sheetText.some((item) => item.includes('特殊物料') && item.includes('不导入'))) throw new Error('特殊物料被当成可导入')
  if (!sheetText.some((item) => item.includes('公用产品') && item.includes('不导入'))) throw new Error('说明表被当成可导入')
  notes.push('四个说明表保持不导入')
  await page.getByRole('button', { name: '预览导入' }).click()
  await page.getByText('可导入 0 行').waitFor()
  await page.getByText(/不能导入 \d+ 行/).waitFor()
  const mid = await page.evaluate(() => {
    const raw = localStorage.getItem('iyge-v2-mock-db')
    if (!raw) return 0
    return JSON.parse(raw).data.skus.filter((item) => item.supplierCode === 'MYEV3CH/A').length
  })
  if (mid !== 0) throw new Error('预览阶段已经写入了真实物料')
  notes.push('预览没有写入')
  await page.getByText('对不上正式规划的行，按临时物料导入').click()
  await page.getByText(/可导入 [1-9]\d* 行/).waitFor({ timeout: 20000 })
  await page.getByText('分成两条').first().waitFor()
  notes.push('重复供应商编码被标出且不合并')
  await page.getByRole('button', { name: /确认导入 \d+ 行/ }).click()
  const resultBox = page.locator('p.muted').filter({ hasText: '新写入' })
  await resultBox.waitFor({ timeout: 60000 })
  const result = await resultBox.innerText()
  if (!result.includes('新写入') || result.includes('新写入 0')) throw new Error(result)
  notes.push(result)
  await page.getByRole('button', { name: /确认导入 \d+ 行/ }).click()
  await page.locator('p.muted').filter({ hasText: '没有重复创建' }).waitFor({ timeout: 60000 })
  const replay = await page.locator('p.muted').filter({ hasText: '没有重复创建' }).innerText()
  const created = Number((replay.match(/新写入 (\d+)/) || [])[1] || -1)
  if (created !== 0) throw new Error('重复确认又写了物料：' + replay)
  notes.push('同一文件再次确认没有新增')
  await page.goto(`${base}/products`, { waitUntil: 'networkidle' })
  const search = page.getByPlaceholder('名称、分类、属性、SKU、OA 编号')
  await search.fill('MYEV3CH/A')
  await search.press('Enter')
  await page.getByText('手机 Apple iPhone 16 128GB 黑色').first().waitFor()
  await page.locator('.el-table__expand-icon').first().click()
  await page.getByText('供应商 MYEV3CH/A').first().waitFor()
  await page.getByText(/TMP-/).first().waitFor()
  notes.push('商品列表能按供应商编码找到黑色物料')
  await page.getByRole('button', { name: '查看物料' }).first().click()
  await page.waitForURL(/\/products\//)
  const supplier = page.locator('label').filter({ hasText: '供应商编码' }).locator('input')
  await supplier.waitFor()
  if ((await supplier.inputValue()) !== 'MYEV3CH/A') throw new Error('物料档案里的供应商编码不对')
  const guanjiapo = page.locator('label').filter({ hasText: '管家婆' }).locator('input')
  if (!(await guanjiapo.inputValue())) throw new Error('物料档案没有管家婆编号')
  notes.push('物料档案保留供应商编码和管家婆编号')
  await page.goto(`${base}/products`, { waitUntil: 'networkidle' })
  const searchAgain = page.getByPlaceholder('名称、分类、属性、SKU、OA 编号')
  await searchAgain.fill('MYEW3CH/A')
  await searchAgain.press('Enter')
  await page.getByText('手机 Apple iPhone 16 128GB 白色').first().waitFor()
  notes.push('白色物料单独存在')
  await page.goto(`${base}/specs?template=t-phone`, { waitUntil: 'networkidle' })
  await page.getByText(/临时物料 \d+ 条/).waitFor()
  await page.getByText(/TMP-/).first().waitFor()
  notes.push('模型页能看到临时物料和规划编号')
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
} catch (error) {
  console.log(notes.map((item) => 'PASS ' + item).join('\n'))
  console.error('FAIL', error)
  process.exitCode = 1
} finally {
  await browser.close()
}
